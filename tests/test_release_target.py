"""`make db-release` must migrate the cluster whose roles it just converged.

Roles are converged over the superuser connection and Alembic runs over
``MARKETAI_DATABASE_URL``. Those are independent strings, and the failure when
they disagree is silent and severe: the check passes on staging, the RLS
migration lands on a production cluster whose roles predate it, and every
application read comes back empty.

Checking the database name, the connected role and the bridge state on the
migration target is necessary but not sufficient -- two clusters prepared the
same way answer all three identically. So convergence stamps the database with
a nonce generated by that run, and the migration is refused unless the target
is carrying it. These tests exercise both halves against a real cluster; CI
additionally cross-wires two fully prepared clusters.
"""

from __future__ import annotations

import contextlib
import io
import os
import unittest

from scripts.domain_bridge import declared_bridge_state

OWNER_URL = os.environ.get("DOMAIN_OWNER_DATABASE_URL")
APP_URL = os.environ.get("DOMAIN_APP_DATABASE_URL")
SUPERUSER_URL = os.environ.get("DOMAIN_SUPERUSER_DATABASE_URL")
WRONG_TARGET_URL = os.environ.get("DOMAIN_WRONG_TARGET_URL")

CONFIGURED = all((OWNER_URL, APP_URL))

SKIP_REASON = (
    "set DOMAIN_OWNER_DATABASE_URL and DOMAIN_APP_DATABASE_URL against a "
    "cluster provisioned with deploy/postgres/apply-roles.sh"
)


@unittest.skipUnless(CONFIGURED, SKIP_REASON)
class ReleaseTargetVerificationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        from sqlalchemy import create_engine, text

        cls.create_engine = staticmethod(create_engine)
        cls.text = staticmethod(text)

    def engine(self, url: str):
        engine = self.create_engine(url, future=True)
        self.addCleanup(engine.dispose)
        return engine

    def stamped_nonce(self) -> str:
        """What the cluster carries, i.e. what provisioning last stamped."""
        with self.engine(OWNER_URL).connect() as conn:
            return conn.execute(
                self.text("SELECT current_setting('marketai.release_nonce', true)")
            ).scalar()

    def verify(self, url: str, *, nonce: str | None = None) -> tuple[int, str]:
        from scripts.verify_release_target import main

        environment = {
            "MARKETAI_DATABASE_URL": url,
            "MARKETAI_RELEASE_NONCE": self.stamped_nonce() if nonce is None else nonce,
        }

        previous = {name: os.environ.get(name) for name in environment}

        def restore() -> None:
            for name, value in previous.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value

        self.addCleanup(restore)
        for name, value in environment.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value

        err = io.StringIO()
        with contextlib.redirect_stderr(err), contextlib.redirect_stdout(io.StringIO()):
            code = main()

        return code, err.getvalue()

    def set_bridge(self, state: str) -> None:
        with self.engine(SUPERUSER_URL).connect() as conn:
            conn.execution_options(isolation_level="AUTOCOMMIT").execute(
                self.text(f"ALTER ROLE marketai_domain_app {state}")
            )

    # ------------------------------------------------------- identity ----

    def test_the_cluster_this_run_converged_passes(self):
        code, message = self.verify(OWNER_URL)

        self.assertEqual(code, 0, message)

    def test_an_identically_prepared_cluster_is_refused(self):
        """The case name, role and bridge state cannot see.

        A second cluster provisioned the same way is the same database name,
        reached as the same role, with the same bridge state. What it does not
        have is the nonce this run stamped -- it has the one its own
        convergence left.
        """
        code, message = self.verify(OWNER_URL, nonce="a" * 32)

        self.assertEqual(code, 1)
        self.assertIn("not the one this release converged", message)
        self.assertIn("same cluster", message)

    @unittest.skipUnless(
        SUPERUSER_URL,
        "changing a role default needs DOMAIN_SUPERUSER_DATABASE_URL",
    )
    def test_a_role_default_cannot_forge_the_database_stamp(self):
        """Identity comes from the database catalog, not the effective GUC.

        PostgreSQL applies role settings after database settings. Reading
        ``current_setting`` therefore lets a stale ``ALTER ROLE ... SET`` (or a
        connection ``options=-c`` value) impersonate the nonce stamped on a
        different database. The verifier must read the database-level setting
        itself.
        """
        forged = "f" * 32

        def reset_role_default() -> None:
            with self.engine(SUPERUSER_URL).connect() as conn:
                conn.execution_options(isolation_level="AUTOCOMMIT").execute(
                    self.text(
                        "ALTER ROLE marketai_domain_owner"
                        " RESET marketai.release_nonce"
                    )
                )

        self.addCleanup(reset_role_default)
        with self.engine(SUPERUSER_URL).connect() as conn:
            conn.execution_options(isolation_level="AUTOCOMMIT").execute(
                self.text(
                    "ALTER ROLE marketai_domain_owner"
                    f" SET marketai.release_nonce = '{forged}'"
                )
            )

        code, message = self.verify(OWNER_URL, nonce=forged)

        self.assertEqual(code, 1)
        self.assertIn("not the one this release converged", message)

    def test_a_target_that_was_never_stamped_is_refused(self):
        code, message = self.verify(OWNER_URL, nonce="")

        self.assertEqual(code, 1)
        self.assertIn("MARKETAI_RELEASE_NONCE is required", message)

    # ---------------------------------------------------------- shape ----

    def test_a_target_reached_as_the_wrong_role_is_refused(self):
        # The runtime role has no DDL; a release pointed at it would fail
        # halfway through the migration instead of before it.
        code, message = self.verify(APP_URL)

        self.assertEqual(code, 1)
        self.assertIn("connects as", message)

    @unittest.skipUnless(
        WRONG_TARGET_URL,
        "set DOMAIN_WRONG_TARGET_URL to a database this release did not prepare",
    )
    def test_a_target_that_is_not_the_domain_database_is_refused(self):
        code, message = self.verify(WRONG_TARGET_URL, nonce="a" * 32)

        self.assertEqual(code, 1)
        self.assertIn("not 'marketai_domain'", message)

    @unittest.skipUnless(
        SUPERUSER_URL, "changing BYPASSRLS needs DOMAIN_SUPERUSER_DATABASE_URL"
    )
    def test_a_target_whose_bridge_state_drifted_is_refused(self):
        declared = declared_bridge_state()
        opposite = "NOBYPASSRLS" if declared == "BYPASSRLS" else "BYPASSRLS"

        self.addCleanup(self.set_bridge, declared)
        self.set_bridge(opposite)

        code, message = self.verify(OWNER_URL)

        self.assertEqual(code, 1)
        self.assertIn("rolbypassrls", message)


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
