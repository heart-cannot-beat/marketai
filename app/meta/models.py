class VerdictSupersessionRecord(Base):
    """Prevents restored historical decisions from becoming current.

    When a new verdict is produced from newer evidence, the old verdict
    is superseded. Restored historical runs do not automatically
    resurrect superseded verdicts -- the supersession record stands.
    """

    __tablename__ = "verdict_supersession_records"
    __table_args__ = (
        UniqueConstraint("superseded_verdict_id",
                         name="uq_vsup_superseded_verdict"),
        CheckConstraint(
            "meta_mode IN ('customer_sandbox', 'controlled_mock', 'internal_validation')",
            name="mode_valid",
        ),
    )

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    workspace_id: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    meta_mode: Mapped[str] = mapped_column(String(32), nullable=False)
    superseded_verdict_id: Mapped[str] = mapped_column(String(64), nullable=False)
    superseding_verdict_id: Mapped[str] = mapped_column(String(64), nullable=False)
    reason: Mapped[str] = mapped_column(String(200), nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow,
    )
