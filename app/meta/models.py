# §3.1 MetaConnectionRecord
# ---------------------------------------------------------------------------

class MetaConnectionRecord(Base):
    __tablename__ = "meta_connection_records"
    __table_args__ = (
        UniqueConstraint("workspace_id", "meta_mode", "id",
                         name="uq_meta_connections_workspace_mode_id"),
        # Composite target for ScaleDeliveryTargetRecord's connection FK
        # (spec §4.3, issue #86 Task 7): added here, not autogenerated,
        # because that is the first consumer that needs ad_account_id
        # folded into the unique target alongside (workspace_id, meta_mode,
        # id). Installed by migrations/versions/ab1_scale_lineage_tables.py.
        UniqueConstraint("workspace_id", "meta_mode", "id", "ad_account_id",
                         name="uq_meta_connections_workspace_mode_id_account"),
        CheckConstraint(
            "(state = 'retired') = (retired_at IS NOT NULL)",
            # Kept short: the project's "ck" naming convention re-prefixes
            # this literal name with ck_<table_name>_, and the combined
            # identifier must stay within PostgreSQL's 63-char limit.
            name="ck_meta_conn_retired_state",
        ),
        CheckConstraint(
            "state IN ('active', 'retiring', 'retired')",
            name="ck_meta_connection_state_valid",
        ),
        CheckConstraint(
            "meta_mode IN ('customer_sandbox', 'controlled_mock', 'internal_validation')",
            name="ck_meta_connection_mode_valid",
        ),
    )

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    workspace_id: Mapped[str] = mapped_column(
        ForeignKey("workspaces.id", ondelete="RESTRICT"), nullable=False, index=True,
    )
    meta_mode: Mapped[str] = mapped_column(String(32), nullable=False)
    ad_account_id: Mapped[str] = mapped_column(String(100), nullable=False)
    state: Mapped[str] = mapped_column(String(32), nullable=False, default="active")
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow,
    )
    retired_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True,
    )


Index(
    "uq_meta_connection_active",
    MetaConnectionRecord.workspace_id,
    MetaConnectionRecord.meta_mode,
    unique=True,
    sqlite_where=text("state = 'active'"),
    postgresql_where=text("state = 'active'"),
)


