"""Regeneration intents: derive a new Draft from an approved AssetVersion (#21 Task 5).

A regeneration is not a fresh Draft that happens to share a Product -- it
carries explicit provenance back to the exact AssetVersion it was requested
from (``source_asset_version_id``) and, when the source was itself produced
by a RunItem, the semantic recipe identity of that production
(``source_recipe_identity``). Both columns already exist on
``GenerationDraftRecord`` (added alongside ``regeneration_intent`` in Task 2)
so this module only has to populate them correctly, never widen the schema.

Four intents are supported, matching the ``regeneration_intent`` /
``intent_kind`` CHECK constraints shared with ``RunItemRecord``:

- ``same_recipe`` -- rerun the exact recipe that produced the source version.
- ``new_seed`` -- rerun the recipe with a new provider seed.
- ``edit_prompt`` -- rerun with caller-supplied prompt/selector overrides.
- ``quality_feedback`` -- rerun in response to QC feedback; requires at least
  one recorded ``AssetQCAttemptRecord`` on the source version, since there is
  nothing to "give feedback" about otherwise.

QC feedback (Issue #169, v9 §3.1 "QC 反馈可以进入下一次配方"): when the
source version's latest quality check failed, every regeneration draft
carries its failed checks -- the Chinese reason and the English ``fix_hint``
the VLM wrote -- under ``selectors.qc_feedback``, plus whatever feedback the
source's own recipe already carried. The Preview freezes them into the new
recipe's ``creative.qc_feedback`` and the prompt adds them as corrections.
The draft runs on the provider/model of the Run that produced the source
(a ``byok`` source is regenerated by its own provider, not the Mock).

``product_id`` is resolved from the source AssetVersion's owning Asset --
the same lookup ``app.generation.review._resolve_asset_and_product`` performs
-- rather than accepted from the caller, since the new Draft belongs to
whichever Product the AssetVersion it regenerates belongs to.
"""
from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.adapters.persistence.models import AssetRecord, AssetVersionRecord, GenerationRunRecord
from app.generation.draft import create_draft
from app.generation.models import (
    AssetQCAttemptRecord,
    AssetQCCheckResultRecord,
    GenerationDraftRecord,
    GenerationRecipeSnapshotRecord,
    RunItemAssetVersionBindingRecord,
    RunItemRecord,
)
from app.generation.review import project_effective_review
from app.platform.tenancy import TenantContext


class RegenerationError(ValueError):
    def __init__(self, code: str, detail: str, *, params: dict | None = None):
        self.code = code
        self.detail = detail
        self.params = params or {}
        super().__init__(f"{code}: {detail}")


#: Mirrors the ``ck_generation_draft_regen_intent`` / ``ck_run_item_intent_kind``
#: CHECK constraints, minus ``new_generation`` (that value means "not a
#: regeneration" and has no entry point here).
VALID_INTENTS = {"same_recipe", "new_seed", "edit_prompt", "quality_feedback"}

#: Review-summary batch actions (Issue #49 Task 7, spec §0.3/§0.4). Each
#: action names both the *effective review value* it draws candidates from
#: and the number of variants it requests per stable-dimension-signature
#: group: "regenerate_needs_changes" (reviewer flagged the group -- produce
#: 2 fresh variants) and "supplement_approved" (the group is already
#: approved -- 3 more variants to round out the set).
_BATCH_REVIEW_FILTER = {
    "regenerate_needs_changes": "needs_changes",
    "supplement_approved": "approved",
}
_BATCH_VARIANT_COUNTS = {
    "regenerate_needs_changes": 2,
    "supplement_approved": 3,
}
VALID_BATCH_ACTIONS = set(_BATCH_REVIEW_FILTER)

#: Every review-summary batch draft reruns with a fresh provider seed --
#: it is asking for *more/different* variants of an existing signature
#: group, not an exact repeat (``same_recipe``) or a QC-triggered rerun
#: (``quality_feedback``, which requires a QC attempt these candidates may
#: not carry).
_BATCH_INTENT_KIND = "new_seed"


def _resolve_source_version(
    session: Session, ctx: TenantContext, source_version_id: str
) -> AssetVersionRecord:
    version = session.execute(
        select(AssetVersionRecord).where(
            AssetVersionRecord.id == source_version_id,
            AssetVersionRecord.workspace_id == ctx.workspace_id,
        )
    ).scalar_one_or_none()
    if version is None:
        raise RegenerationError(
            "source_not_found", f"AssetVersion {source_version_id} not found"
        )
    return version


def _resolve_product_id(session: Session, ctx: TenantContext, asset_id: str) -> str:
    asset = session.execute(
        select(AssetRecord).where(
            AssetRecord.id == asset_id,
            AssetRecord.workspace_id == ctx.workspace_id,
        )
    ).scalar_one_or_none()
    if asset is None:
        raise RegenerationError("asset_not_found", f"Asset {asset_id} not found")
    return asset.product_id


def _require_qc_attempt(
    session: Session, ctx: TenantContext, source_version_id: str
) -> None:
    qc = session.execute(
        select(AssetQCAttemptRecord.id).where(
            AssetQCAttemptRecord.asset_version_id == source_version_id,
            AssetQCAttemptRecord.workspace_id == ctx.workspace_id,
        ).limit(1)
    ).scalar_one_or_none()
    if qc is None:
        raise RegenerationError(
            "qc_attempt_required",
            "quality_feedback requires a QC attempt on the source AssetVersion",
        )


#: At most this many feedback entries travel with one regeneration draft.
MAX_QC_FEEDBACK_ENTRIES = 6


def _source_run(
    session: Session, ctx: TenantContext, version: AssetVersionRecord
) -> GenerationRunRecord | None:
    if not version.producing_run_item_id:
        return None
    item = session.execute(
        select(RunItemRecord).where(
            RunItemRecord.id == version.producing_run_item_id,
            RunItemRecord.workspace_id == ctx.workspace_id,
        )
    ).scalar_one_or_none()
    if item is None:
        return None
    return session.execute(
        select(GenerationRunRecord).where(
            GenerationRunRecord.id == item.generation_run_id,
            GenerationRunRecord.workspace_id == ctx.workspace_id,
        )
    ).scalar_one_or_none()


def source_qc_feedback(
    session: Session, ctx: TenantContext, version: AssetVersionRecord
) -> list[dict]:
    """QC feedback a regeneration of ``version`` carries (Issue #169).

    The failed checks of the version's latest QC attempt (newest evidence
    first), then the feedback the version's own recipe was generated with,
    deduplicated by hint. Empty when the latest check did not fail.
    """
    latest = session.execute(
        select(AssetQCAttemptRecord)
        .where(
            AssetQCAttemptRecord.workspace_id == ctx.workspace_id,
            AssetQCAttemptRecord.asset_version_id == version.id,
        )
        .order_by(AssetQCAttemptRecord.attempt_sequence.desc())
        .limit(1)
    ).scalar_one_or_none()
    if latest is None or latest.state not in ("failed_blocking", "failed_nonblocking"):
        return []
    entries: list[dict] = []
    checks = session.execute(
        select(AssetQCCheckResultRecord)
        .where(
            AssetQCCheckResultRecord.workspace_id == ctx.workspace_id,
            AssetQCCheckResultRecord.qc_attempt_id == latest.id,
            AssetQCCheckResultRecord.outcome == "fail",
        )
        .order_by(AssetQCCheckResultRecord.created_at, AssetQCCheckResultRecord.id)
    ).scalars().all()
    for check in checks:
        evidence = check.evidence_json or {}
        hint = str(evidence.get("fix_hint") or "").strip()
        if not hint:
            continue
        entries.append({
            "hint": hint,
            "reason": check.feedback_detail or str(evidence.get("reason") or ""),
            "rule_id": check.rule_id,
            "source_asset_version_id": version.id,
            "qc_attempt_id": latest.id,
        })
    run = _source_run(session, ctx, version)
    if run is not None and run.recipe_snapshot_id:
        snapshot = session.execute(
            select(GenerationRecipeSnapshotRecord).where(
                GenerationRecipeSnapshotRecord.id == run.recipe_snapshot_id,
                GenerationRecipeSnapshotRecord.workspace_id == ctx.workspace_id,
            )
        ).scalar_one_or_none()
        creative = ((snapshot.canonical_json or {}) if snapshot is not None else {}).get("creative")
        for entry in (creative or {}).get("qc_feedback") or [] if isinstance(creative, dict) else []:
            if isinstance(entry, dict) and str(entry.get("hint") or "").strip():
                entries.append(dict(entry))
    unique: list[dict] = []
    seen: set[str] = set()
    for entry in entries:
        key = str(entry["hint"]).strip().lower()
        if key in seen:
            continue
        seen.add(key)
        unique.append(entry)
    return unique[:MAX_QC_FEEDBACK_ENTRIES]


def _resolve_source_recipe_identity(
    session: Session, ctx: TenantContext, source_version_id: str
) -> str | None:
    """The semantic fingerprint of the RunItem that produced ``source_version_id``.

    ``None`` when the source version has no ``produced`` binding (e.g. it was
    uploaded rather than generated) -- regeneration still proceeds, it simply
    has no recipe to carry forward.
    """
    binding = session.execute(
        select(RunItemAssetVersionBindingRecord).where(
            RunItemAssetVersionBindingRecord.asset_version_id == source_version_id,
            RunItemAssetVersionBindingRecord.workspace_id == ctx.workspace_id,
            RunItemAssetVersionBindingRecord.kind == "produced",
        )
    ).scalar_one_or_none()
    if binding is None:
        return None

    item = session.execute(
        select(RunItemRecord).where(
            RunItemRecord.id == binding.run_item_id,
            RunItemRecord.workspace_id == ctx.workspace_id,
        )
    ).scalar_one_or_none()
    return item.semantic_fingerprint if item else None


def _resolve_stable_dimension_signature(
    session: Session, ctx: TenantContext, source_version_id: str
) -> str:
    """The ``stable_dimension_signature`` of the RunItem that produced
    ``source_version_id`` (Issue #49 Task 7, spec §0.4).

    ``AssetVersionRecord`` carries no ``stable_dimension_signature`` column
    of its own (see ``app.generation.asset_queries``'s "No column yet"
    notes) -- the signature lives on ``RunItemRecord``, so this walks the
    same ``produced`` binding :func:`_resolve_source_recipe_identity` does.
    Returns ``""`` (the column's own default) when the source version has
    no producing RunItem binding to resolve -- e.g. an uploaded version --
    or when the producing RunItem's own signature is unset. This is a raw
    resolver, not a validation gate: :func:`create_review_summary_regeneration`
    treats an empty result as a fatal ``missing_signature`` per spec §0.6,
    while :func:`batch_item_from_draft`'s replay reconstruction calls it
    purely to report the historical value.
    """
    binding = session.execute(
        select(RunItemAssetVersionBindingRecord).where(
            RunItemAssetVersionBindingRecord.asset_version_id == source_version_id,
            RunItemAssetVersionBindingRecord.workspace_id == ctx.workspace_id,
            RunItemAssetVersionBindingRecord.kind == "produced",
        )
    ).scalar_one_or_none()
    if binding is None:
        return ""

    item = session.execute(
        select(RunItemRecord).where(
            RunItemRecord.id == binding.run_item_id,
            RunItemRecord.workspace_id == ctx.workspace_id,
        )
    ).scalar_one_or_none()
    return item.stable_dimension_signature if item else ""


def create_regeneration_draft(
    session: Session,
    ctx: TenantContext,
    source_version_id: str,
    intent_kind: str,
    *,
    prompt_overrides: dict | None = None,
    qc_attempt_id: str | None = None,
    variant_count: int | None = None,
) -> GenerationDraftRecord:
    """Create a new editable Draft that regenerates ``source_version_id``.

    Raises :class:`RegenerationError` with code ``invalid_intent`` for an
    unsupported ``intent_kind``, ``source_not_found`` when the source
    AssetVersion does not resolve inside ``ctx.workspace_id``, or
    ``qc_attempt_required`` when ``intent_kind == "quality_feedback"`` and the
    source version carries no QC attempt.

    ``variant_count``, when given, is recorded on the Draft's
    ``combination_strategy_json`` as ``requested_variant_count`` (Issue #49
    Task 7's review-summary batch calls this to pin how many variants the
    batch requested per stable-dimension-signature group) -- ``None`` leaves
    ``combination_strategy`` exactly as before, so every pre-existing caller
    is unaffected.
    """
    if intent_kind not in VALID_INTENTS:
        raise RegenerationError("invalid_intent", f"Unknown intent: {intent_kind!r}")

    version = _resolve_source_version(session, ctx, source_version_id)
    product_id = _resolve_product_id(session, ctx, version.asset_id)

    if intent_kind == "quality_feedback":
        _require_qc_attempt(session, ctx, source_version_id)

    source_recipe_identity = _resolve_source_recipe_identity(
        session, ctx, source_version_id
    )

    combination_strategy = {"kind": "full", "planner_version": "v1"}
    if variant_count is not None:
        combination_strategy["requested_variant_count"] = variant_count

    selectors = dict(prompt_overrides or {})
    feedback = source_qc_feedback(session, ctx, version)
    if feedback:
        selectors["qc_feedback"] = feedback

    execution_mode = version.execution_mode or "mock"
    provider, model = "mock", "mock-v1"
    source_run = _source_run(session, ctx, version)
    if execution_mode != "mock" and source_run is not None and source_run.provider:
        provider, model = source_run.provider, source_run.model

    return create_draft(
        session,
        ctx,
        product_id=product_id,
        provider=provider,
        model=model,
        execution_mode=execution_mode,
        combination_strategy=combination_strategy,
        selectors=selectors or prompt_overrides,
        regeneration_intent=intent_kind,
        source_asset_version_id=source_version_id,
        source_recipe_identity=source_recipe_identity,
    )


def batch_item_from_draft(
    session: Session, ctx: TenantContext, draft: GenerationDraftRecord
) -> dict:
    """Reconstruct one review-summary batch response item from an already-
    created Draft -- the shape :func:`create_review_summary_regeneration`
    returns for a fresh create, and what a replay of
    ``POST /generation/regeneration-draft-batches`` rebuilds from the
    persisted Draft ids the first call committed (Issue #49 Task 7).
    """
    strategy = draft.combination_strategy_json or {}
    signature = (
        _resolve_stable_dimension_signature(session, ctx, draft.source_asset_version_id)
        if draft.source_asset_version_id
        else ""
    )
    return {
        "generation_draft_id": draft.id,
        "source_asset_version_id": draft.source_asset_version_id,
        "stable_dimension_signature": signature,
        "requested_variant_count": strategy.get("requested_variant_count"),
    }


def create_review_summary_regeneration(
    session: Session,
    ctx: TenantContext,
    *,
    action: str,
    candidate_version_ids: list[str],
) -> list[dict]:
    """Atomic review-summary batch: group ``candidate_version_ids`` by
    stable-dimension-signature and create one regeneration Draft per group
    (Issue #49 Task 7, spec §0.3/§0.4). Browser Task 10's ``ReviewSummary``
    is the consumer.

    ``action`` selects both the *effective review value* every candidate
    must currently carry and the number of variants requested per group
    (:data:`_BATCH_VARIANT_COUNTS`):

    - ``"regenerate_needs_changes"`` -- every candidate's *effective* review
      (``app.generation.review.project_effective_review``) must be
      ``needs_changes``; 2 variants per signature group.
    - ``"supplement_approved"`` -- every candidate's effective review must
      be ``approved``; 3 variants per signature group.

    Every id in ``candidate_version_ids`` must resolve to an AssetVersion in
    ``ctx.workspace_id``, carry the action's required *effective review*
    value, and resolve a non-empty ``stable_dimension_signature`` -- per
    spec §0.6 ("a stale, cross-Workspace, wrong-review, missing-signature,
    or ineligible candidate fails the whole command with a stable code"), a
    single candidate failing any of those checks raises
    ``RegenerationError`` (``candidate_not_found``, ``wrong_review``, or
    ``missing_signature`` respectively) and fails the WHOLE batch before any
    Draft is created (the caller's ``tenant_session`` unit of work then
    rolls back the whole transaction, matching the "atomic" contract).

    Within each signature group the *newest* version
    (``created_at DESC, id DESC``) is chosen as the regeneration source --
    the source producer the group's fresh variants are most likely to still
    resemble.

    Returns the created batch items in a deterministic order (by
    ``stable_dimension_signature``), each shaped like
    :func:`batch_item_from_draft`'s output.
    """
    if action not in VALID_BATCH_ACTIONS:
        raise RegenerationError(
            "invalid_action", f"Unknown review-summary action: {action!r}"
        )
    if not candidate_version_ids:
        raise RegenerationError(
            "no_candidates", "candidate_version_ids must not be empty"
        )

    versions: dict[str, AssetVersionRecord] = {}
    for version_id in candidate_version_ids:
        version = session.execute(
            select(AssetVersionRecord).where(
                AssetVersionRecord.id == version_id,
                AssetVersionRecord.workspace_id == ctx.workspace_id,
            )
        ).scalar_one_or_none()
        if version is None:
            raise RegenerationError(
                "candidate_not_found",
                f"AssetVersion {version_id} not found in this Workspace",
            )
        versions[version_id] = version

    # Spec §0.6: a stale, cross-Workspace, wrong-review, missing-signature,
    # or ineligible candidate fails the WHOLE command. Validate every
    # candidate up front, before any Draft is created, so one bad candidate
    # fails the whole batch rather than being silently dropped from it.
    required_review_value = _BATCH_REVIEW_FILTER[action]
    signatures: dict[str, str] = {}
    for version_id in candidate_version_ids:
        effective_review = project_effective_review(session, ctx, version_id)
        if effective_review != required_review_value:
            raise RegenerationError(
                "wrong_review",
                f"AssetVersion {version_id} has effective review "
                f"{effective_review!r}, required {required_review_value!r} "
                f"for action {action!r}",
            )
        signature = _resolve_stable_dimension_signature(session, ctx, version_id)
        if not signature:
            raise RegenerationError(
                "missing_signature",
                f"AssetVersion {version_id} has no resolvable "
                "stable_dimension_signature",
            )
        signatures[version_id] = signature

    groups: dict[str, list[AssetVersionRecord]] = {}
    for version_id, version in versions.items():
        groups.setdefault(signatures[version_id], []).append(version)

    variant_count = _BATCH_VARIANT_COUNTS[action]

    drafts: list[GenerationDraftRecord] = []
    results = []
    for signature in sorted(groups):
        group_versions = sorted(
            groups[signature], key=lambda v: (v.created_at, v.id), reverse=True
        )
        source_version = group_versions[0]

        draft = create_regeneration_draft(
            session,
            ctx,
            source_version.id,
            _BATCH_INTENT_KIND,
            variant_count=variant_count,
        )
        drafts.append(draft)
        results.append(batch_item_from_draft(session, ctx, draft))

    # Idempotency (Issue #49 Task 7 review, Finding 2): the batch route binds
    # a single VARCHAR(100) response_resource_id to this whole create, which
    # cannot hold every created Draft id once a batch spans 3+ signature
    # groups (35-char "gd_..." ids overflow past two groups). Stash the full
    # ordered id list on each Draft's own combination_strategy_json instead
    # -- an existing JSON column, no schema change -- so the route can bind
    # just the *first* Draft's id (always well under 100 chars) and still
    # reconstruct every sibling on replay (see batch_item_from_draft's
    # caller in v1_router.py). This mutates the freshly-created,
    # not-yet-committed Draft rows still inside this same atomic
    # batch-create transaction -- no other session can observe or race them
    # yet -- so it deliberately does not go through update_draft's CAS path;
    # that path exists for concurrency-safe updates to an already-exposed
    # Draft, which these are not until this transaction commits.
    if drafts:
        draft_ids = [draft.id for draft in drafts]
        for draft in drafts:
            strategy = dict(draft.combination_strategy_json or {})
            strategy["batch_draft_ids"] = draft_ids
            draft.combination_strategy_json = strategy
        session.flush()

    return results
