"""BlobStore protocol and shared value objects (spec §7.3-§7.4).

`BlobStore` is a Deep Module: FastAPI and the Worker depend only on this
Protocol and its value objects. `S3BlobStore`
(`app/adapters/blob_store_s3.py`) is the versioned-S3 Adapter,
`RailwayBucketBlobStore` (`app/adapters/blob_store_railway_bucket.py`) is the
versionless Railway production Adapter, and `LocalFileBlobStore`
(`app/adapters/blob_store_local.py`) is the dev-only filesystem Adapter whose
signed URLs point at the separate `LocalBlobTransferApp`
(`worker/local_blob_transfer.py`).

Binary data never transits FastAPI or Next.js memory (spec §7.1): the
browser uploads/downloads directly to storage using short-lived signed
capabilities that this module's Adapters issue. Object keys are always
generated by the server (`app/platform/blob_store.derive_committed_key` and
callers of this module) -- the browser cannot supply arbitrary paths.

Interface guarantee (spec §7.4): `commit_upload` either commits the exact
bytes described by `InspectedUpload`, or raises a documented
`BlobStoreError`. It never commits a different revision. Callers depend only
on this shared guarantee; an Adapter may offer a stronger outcome (e.g. S3
can still address an old `VersionId`) without changing the caller contract.

Signed URLs are short-lived bearer capabilities and must never appear in
logs (Global Constraint) -- callers should log only the object key, not the
`UploadGrant`/`DownloadGrant` `url`/`fields`/`headers`.
"""
from __future__ import annotations

import re
from collections.abc import AsyncIterator
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Literal, Protocol, runtime_checkable
from urllib.parse import quote


# --------------------------------------------------------------------------
# Value objects (spec §7.3)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class UploadSpec:
    staging_key: str
    content_type: str
    content_length_min: int
    content_length_max: int
    checksum_sha256_b64: str
    expires_in_seconds: int


@dataclass(frozen=True)
class PresignedPostGrant:
    kind: Literal["presigned_post"]
    url: str
    fields: dict[str, str]  # multipart form fields for POST policy
    expires_at: datetime


@dataclass(frozen=True)
class SignedPutGrant:
    kind: Literal["signed_put"]
    url: str
    headers: dict[str, str]  # HTTP headers for PUT request
    expires_at: datetime


UploadGrant = PresignedPostGrant | SignedPutGrant


@dataclass(frozen=True)
class StagedBlobRef:
    staging_key: str


@dataclass(frozen=True)
class InspectedUpload:
    ref: StagedBlobRef
    storage_revision: str
    size_bytes: int
    checksum_sha256_b64: str
    content_type_declared: str
    magic_bytes: bytes


@dataclass(frozen=True)
class ObjectConstraints:
    expected_size: int
    expected_checksum_sha256_b64: str
    expected_magic_mime: str
    storage_revision: str


@dataclass(frozen=True)
class CommittedBlobRef:
    committed_key: str
    storage_version_id: str
    size_bytes: int
    checksum_sha256_b64: str
    content_type_verified: str


@dataclass(frozen=True)
class DownloadSpec:
    filename: str
    expires_in_seconds: int


@dataclass(frozen=True)
class DownloadGrant:
    url: str
    expires_at: datetime
    content_disposition: str


@dataclass(frozen=True)
class BlobRef:
    key: str
    version_id: str | None = None


@dataclass(frozen=True)
class GeneratedArtifactSpec:
    """Server-owned artifact to commit directly, bypassing staging/inspect.

    Unlike `UploadSpec` (a browser-originated upload that must be inspected
    and magic-byte verified before commit -- spec §7.5), a generated
    artifact (e.g. the Worker's export ZIP, Task 9) is produced entirely
    server-side. The caller already knows its exact `content_type` and has
    computed `expected_sha256_b64` from the bytes it is about to hand off,
    so `BlobStore.commit_generated_artifact` trusts and records both rather
    than re-deriving them.
    """

    committed_key: str
    content_type: str
    expected_sha256_b64: str


# --------------------------------------------------------------------------
# Errors
# --------------------------------------------------------------------------


class BlobStoreError(Exception):
    pass


class ObjectNotFoundError(BlobStoreError):
    pass


class ObjectChangedError(BlobStoreError):
    pass


class RevisionGoneError(BlobStoreError):
    pass


# --------------------------------------------------------------------------
# Protocol
# --------------------------------------------------------------------------


@runtime_checkable
class BlobStore(Protocol):
    async def issue_upload(self, spec: UploadSpec) -> UploadGrant: ...

    async def inspect_upload(self, ref: StagedBlobRef) -> InspectedUpload: ...

    async def commit_upload(
        self,
        inspected: InspectedUpload,
        expected: ObjectConstraints,
    ) -> CommittedBlobRef: ...

    async def issue_download(
        self,
        ref: CommittedBlobRef,
        spec: DownloadSpec,
    ) -> DownloadGrant: ...

    async def delete(self, ref: BlobRef) -> None: ...

    def open_committed(self, ref: CommittedBlobRef) -> AsyncIterator[bytes]: ...

    async def commit_generated_artifact(
        self, source: Path, spec: GeneratedArtifactSpec
    ) -> CommittedBlobRef: ...


# --------------------------------------------------------------------------
# Object key structure (spec §7.13) -- shared by every Adapter
# --------------------------------------------------------------------------

#: Non-leaf key segments (`workspace_id`, `purpose`, date parts):
#: alphanumeric, `_`, `-` only. No `/`, `..`, `\0`, or control characters.
_KEY_SEGMENT_RE = re.compile(r"^[a-zA-Z0-9_-]+$")

#: The leaf segment additionally carries a `.`-delimited extension, e.g.
#: `01h....dat` (staging) or `01h....png` (committed).
_KEY_LEAF_RE = re.compile(r"^[a-zA-Z0-9_-]+\.[a-zA-Z0-9]+$")

#: `Content-Type` (magic-byte verified) -> committed key extension (spec
#: §7.13, §7.5's `PURPOSE_POLICIES` allowlists). `application/octet-stream`
#: is the local Adapter's fallback declared type, never a committable
#: verified MIME, but is mapped defensively so `derive_committed_key` never
#: raises on it.
_MIME_EXTENSIONS: dict[str, str] = {
    "image/png": "png",
    "image/jpeg": "jpg",
    "image/webp": "webp",
    "image/gif": "gif",
    "application/zip": "zip",
    "application/pdf": "pdf",
    "application/json": "json",
    "text/csv": "csv",
    "application/octet-stream": "bin",
}


def validate_object_key(key: str) -> None:
    """Reject any key that is not exactly `prefix/.../leaf.ext`.

    Raises `ValueError` on empty segments, `.`/`..` traversal, control
    characters, absolute paths, or a segment outside the allowed alphabet.
    This is the single point every Adapter routes key validation through
    (spec §7.16: "Path traversal in key components | Rejected at key
    construction time").
    """
    if not key or "\x00" in key or key != key.strip() or key.startswith("/") or key.endswith("/"):
        raise ValueError(f"invalid object key: {key!r}")
    parts = key.split("/")
    if len(parts) < 2:
        raise ValueError(f"invalid object key: {key!r}")
    for part in parts:
        if part in ("", ".", ".."):
            raise ValueError(f"invalid object key segment {part!r} in {key!r}")
    for part in parts[:-1]:
        if not _KEY_SEGMENT_RE.match(part):
            raise ValueError(f"invalid object key segment {part!r} in {key!r}")
    if not _KEY_LEAF_RE.match(parts[-1]):
        raise ValueError(f"invalid object key leaf {parts[-1]!r} in {key!r}")


def extension_for_mime(mime: str) -> str:
    """Map a magic-byte-verified MIME type to a committed key extension."""
    return _MIME_EXTENSIONS.get(mime, "bin")


def derive_committed_key(staging_key: str, verified_mime: str) -> str:
    """Derive the `committed/...` key for a `staging/...` key (spec §7.13).

    Same `{workspace_id}/{purpose}/{YYYY}/{MM}/{DD}/{ulid}` path, extension
    replaced by the magic-byte-verified MIME type rather than the opaque
    `.dat` staging suffix.
    """
    validate_object_key(staging_key)
    parts = staging_key.split("/")
    if parts[0] != "staging":
        raise ValueError(f"not a staging key: {staging_key!r}")
    parts[0] = "committed"
    leaf = parts[-1]
    stem = leaf.rsplit(".", 1)[0]
    parts[-1] = f"{stem}.{extension_for_mime(verified_mime)}"
    committed_key = "/".join(parts)
    validate_object_key(committed_key)
    return committed_key


def content_disposition_header(filename: str) -> str:
    """RFC 6266 `Content-Disposition` from a user-supplied filename.

    Strips control characters and path separators (spec §7.13: "a safe
    Content-Disposition header is generated from filename_original ...
    stripped of control characters and path separators") and carries a
    UTF-8 `filename*` parameter alongside an ASCII fallback.
    """
    sanitized = "".join(ch for ch in filename if ch.isprintable() and ch not in "/\\")
    sanitized = sanitized.strip() or "download"
    ascii_fallback = sanitized.encode("ascii", "replace").decode("ascii").replace('"', "'")
    quoted_utf8 = quote(sanitized, safe="")
    return f'attachment; filename="{ascii_fallback}"; filename*=UTF-8\'\'{quoted_utf8}'
