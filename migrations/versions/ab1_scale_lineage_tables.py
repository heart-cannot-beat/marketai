def _is_postgres() -> bool:
    return op.get_bind().dialect.name == "postgresql"


def _add_upstream_unique_constraints() -> None:
    from collections import defaultdict

    by_table: dict[str, list[tuple[str, list[str]]]] = defaultdict(list)
    for table, name, columns in _UPSTREAM_UNIQUE_CONSTRAINTS:
        by_table[table].append((name, columns))

    # m23b creates its tables from the live ORM metadata.  On a fresh install,
    # that historical migration therefore already includes constraints added
    # to the models for this revision; an upgraded install still needs ab1 to
    # add them.  Reflect first so both paths converge without trying to create
    # a second PostgreSQL backing index with the same relation name.
    inspector = sa.inspect(op.get_bind())
    for table, constraints in by_table.items():
        existing = {
            constraint["name"]: tuple(constraint["column_names"])
            for constraint in inspector.get_unique_constraints(table)
            if constraint.get("name") is not None
        }
        missing: list[tuple[str, list[str]]] = []
        for name, columns in constraints:
            existing_columns = existing.get(name)
            if existing_columns is None:
                missing.append((name, columns))
                continue
            if existing_columns != tuple(columns):
                raise RuntimeError(
                    f"unique constraint {name!r} on {table!r} has columns "
                    f"{existing_columns!r}, expected {tuple(columns)!r}"
                )

        if not missing:
            continue
        with op.batch_alter_table(table, schema=None) as batch_op:
            for name, columns in missing:
                batch_op.create_unique_constraint(name, columns)


def _drop_upstream_unique_constraints() -> None:
    from collections import defaultdict

    by_table: dict[str, list[str]] = defaultdict(list)
    for table, name, _columns in _UPSTREAM_UNIQUE_CONSTRAINTS:
        by_table[table].append(name)
    for table, names in by_table.items():
        with op.batch_alter_table(table, schema=None) as batch_op:
            for name in reversed(names):
                batch_op.drop_constraint(name, type_="unique")


def _add_enrollment_columns() -> None:
    with op.batch_alter_table("scale_enrollments", schema=None) as batch_op:
        for name, col_type, nullable in _ENROLLMENT_NEW_COLUMNS:
            batch_op.add_column(sa.Column(name, col_type, nullable=nullable))


def _drop_enrollment_columns() -> None:
    with op.batch_alter_table("scale_enrollments", schema=None) as batch_op:
        for name, _col_type, _nullable in reversed(_ENROLLMENT_NEW_COLUMNS):
            batch_op.drop_column(name)


def _create_tables() -> None:
    bind = op.get_bind()
    for model in _TABLES_IN_DEPENDENCY_ORDER:
        model.__table__.create(bind=bind, checkfirst=False)


def _drop_tables() -> None:
    for model in reversed(_TABLES_IN_DEPENDENCY_ORDER):
        op.drop_table(model.__tablename__)


def _install_rls_and_grants() -> None:
    if not _is_postgres():
        # SQLite: the repository layer is the only enforcement available,
        # same as every other tenant-owned table in this project.
        return

    for model in _TABLES_IN_DEPENDENCY_ORDER:
        table = model.__tablename__
        # FORCE applies the policy to the table owner too -- belt and
        # braces against a migration-role mistake reading across tenants
        # or Meta modes.
        op.execute(f'ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY')
        op.execute(f'ALTER TABLE "{table}" FORCE ROW LEVEL SECURITY')
        op.execute(f'DROP POLICY IF EXISTS tenant_isolation ON "{table}"')
        op.execute(
            f"""
            CREATE POLICY tenant_isolation ON "{table}"
            USING (marketai_meta_context_is_current(workspace_id, meta_mode))
            WITH CHECK (marketai_meta_context_is_current(workspace_id, meta_mode))
            """
        )
        # Every table here is INSERT-only from application code: scale_
        # delivery_targets is populated once by the (future) population
        # path and never updated in place; scale_command_journal is
        # append-only by construction (claim_command() never updates a
        # row); scale_lineage_guards is only ever inserted by
        # get_or_create_lineage_guard() -- its revision/updated_at columns
        # are advanced solely by the SECURITY DEFINER trigger function
        # below, which runs as the table owner and needs no runtime-role
        # UPDATE grant. No UPDATE grant for any of them.
        op.execute(
            f'GRANT SELECT, INSERT ON TABLE "{table}" '
            "TO marketai_domain_api, marketai_domain_worker"
        )
        op.execute(f'GRANT SELECT ON TABLE "{table}" TO marketai_domain_readonly')


def _uninstall_rls_and_grants() -> None:
    if not _is_postgres():
        return

    for model in reversed(_TABLES_IN_DEPENDENCY_ORDER):
        table = model.__tablename__
        op.execute(
            f'REVOKE ALL ON TABLE "{table}" FROM '
            "marketai_domain_api, marketai_domain_worker, marketai_domain_readonly"
        )
        op.execute(f'DROP POLICY IF EXISTS tenant_isolation ON "{table}"')
        op.execute(f'ALTER TABLE "{table}" NO FORCE ROW LEVEL SECURITY')
        op.execute(f'ALTER TABLE "{table}" DISABLE ROW LEVEL SECURITY')


#: (table, trigger event, trigger name) -- every eligibility-affecting
#: upstream table the spec §7.3 bullet list names, each dispatched by
#: ``TG_TABLE_NAME`` inside the one shared function below. Grouped here so
#: install/uninstall stay in lockstep and downgrade can iterate the same
#: list in reverse.
_BUMP_TRIGGER_SPECS = (
    ("experiment_decisions", "AFTER INSERT OR UPDATE", "trg_bump_slg_on_decision"),
    ("decision_confirmations", "AFTER INSERT", "trg_bump_slg_on_confirmation"),
    ("experiment_eligibility_events", "AFTER INSERT", "trg_bump_slg_on_eligibility_event"),
    ("quality_reviews", "AFTER INSERT", "trg_bump_slg_on_quality_review"),
    ("library_versions", "AFTER UPDATE", "trg_bump_slg_on_library_version"),
    ("market_asset_bindings", "AFTER UPDATE", "trg_bump_slg_on_binding"),
    ("meta_connection_records", "AFTER UPDATE", "trg_bump_slg_on_connection"),
    (
        "observation_contract_generation_records", "AFTER UPDATE",
        "trg_bump_slg_on_contract_generation",
    ),
    ("evidence_attestation_records", "AFTER INSERT OR UPDATE", "trg_bump_slg_on_attestation"),
)

_BUMP_FUNCTION_SQL = """
CREATE OR REPLACE FUNCTION marketai_bump_scale_lineage_guards()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    -- Each branch matches one spec §7.3 bullet. NEW's shape differs per
    -- source table; PL/pgSQL trigger functions bind NEW as a RECORD, so
    -- referencing a column that only exists on the table this branch
    -- guards (via TG_TABLE_NAME) is resolved per-invocation, not at
    -- function-definition time.
    IF TG_TABLE_NAME = 'experiment_decisions' THEN
        -- Winner decision (re)written.
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND winner_decision_id = NEW.id;

    ELSIF TG_TABLE_NAME = 'decision_confirmations' THEN
        -- Winner confirmation created.
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND winner_confirmation_id = NEW.id;

    ELSIF TG_TABLE_NAME = 'experiment_eligibility_events' THEN
        -- Eligibility event: locate guards through the decision(s) sharing
        -- this event's experiment_version (and candidate, when the event
        -- names one).
        UPDATE public.scale_lineage_guards AS g
        SET revision = g.revision + 1, updated_at = now()
        FROM public.experiment_decisions AS d
        WHERE d.workspace_id = NEW.workspace_id
          AND d.experiment_version_id = NEW.experiment_version_id
          AND (NEW.candidate_id IS NULL
               OR d.experiment_version_candidate_id = NEW.candidate_id)
          AND g.workspace_id = d.workspace_id
          AND g.winner_decision_id = d.id;

    ELSIF TG_TABLE_NAME = 'quality_reviews' THEN
        -- QualityReview insert/supersession for the AssetVersion: reviews
        -- are keyed by asset_id, not asset_version_id, so join through
        -- asset_versions to find guards for any version of that asset.
        UPDATE public.scale_lineage_guards AS g
        SET revision = g.revision + 1, updated_at = now()
        FROM public.asset_versions AS av
        WHERE av.workspace_id = NEW.workspace_id
          AND av.asset_id = NEW.asset_id
          AND g.workspace_id = av.workspace_id
          AND g.asset_version_id = av.id;

    ELSIF TG_TABLE_NAME = 'library_versions' THEN
        -- Product/Offer lifecycle or rights/truth change.
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND (product_version_id = NEW.id OR offer_version_id = NEW.id);

    ELSIF TG_TABLE_NAME = 'market_asset_bindings' THEN
        -- MarketAssetBinding change.
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND market_asset_binding_id = NEW.id;

    ELSIF TG_TABLE_NAME = 'meta_connection_records' THEN
        -- MetaConnection change.
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND meta_mode = NEW.meta_mode
          AND meta_connection_id = NEW.id;

    ELSIF TG_TABLE_NAME = 'observation_contract_generation_records' THEN
        -- Contract-generation retirement (and currency/timezone change,
        -- which is recorded on this same row).
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND meta_mode = NEW.meta_mode
          AND contract_generation_id = NEW.id;

    ELSIF TG_TABLE_NAME = 'evidence_attestation_records' THEN
        -- Attestation creation/invalidation: the guard has no direct
        -- attestation column, so match on the generation it attests.
        UPDATE public.scale_lineage_guards
        SET revision = revision + 1, updated_at = now()
        WHERE workspace_id = NEW.workspace_id
          AND meta_mode = NEW.meta_mode
          AND contract_generation_id = NEW.contract_generation_id;
    END IF;

    RETURN NEW;
END;
$$
"""


def _install_bump_trigger() -> None:
    if not _is_postgres():
        # SQLite: no trigger mechanism here. A later task's mutation
        # modules call the equivalent bump logic explicitly in Python for
        # the SQLite/test path (spec §7.3); PostgreSQL trigger tests are
        # authoritative for this mechanism, matching every other
        # PostgreSQL-only trigger in this project (see
        # tests/test_localization_triggers.py's module docstring).
        return

    op.execute(_BUMP_FUNCTION_SQL)
    op.execute("REVOKE ALL ON FUNCTION marketai_bump_scale_lineage_guards() FROM PUBLIC")

    for table, event, trigger_name in _BUMP_TRIGGER_SPECS:
        op.execute(f'DROP TRIGGER IF EXISTS "{trigger_name}" ON "{table}"')
        op.execute(
            f'CREATE TRIGGER "{trigger_name}" {event} ON "{table}" '
            'FOR EACH ROW EXECUTE FUNCTION marketai_bump_scale_lineage_guards()'
        )


def _uninstall_bump_trigger() -> None:
    if not _is_postgres():
        return

    for table, _event, trigger_name in reversed(_BUMP_TRIGGER_SPECS):
        op.execute(f'DROP TRIGGER IF EXISTS "{trigger_name}" ON "{table}"')
    op.execute("DROP FUNCTION IF EXISTS marketai_bump_scale_lineage_guards()")


def upgrade() -> None:
    _add_upstream_unique_constraints()
    _create_tables()
    _add_enrollment_columns()
    _install_rls_and_grants()
    _install_bump_trigger()


def downgrade() -> None:
    _uninstall_bump_trigger()
    _uninstall_rls_and_grants()
    _drop_enrollment_columns()
    _drop_tables()
    _drop_upstream_unique_constraints()
