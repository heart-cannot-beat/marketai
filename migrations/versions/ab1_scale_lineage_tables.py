"""Scale Enrollment lineage tables (issue #86 hardening).

Revision ID: ab1_scale_lineage
Revises: aa1_identity_kind

Task 7 creates ``scale_delivery_targets`` (spec §4.3), the first of six
tables this migration eventually holds. Task 8 appends
``ScaleCommandJournalRecord`` (spec §7.1) and ``ScaleLineageGuardRecord``
(spec §7.3) to ``_TABLES_IN_DEPENDENCY_ORDER`` below, plus the PostgreSQL
``marketai_bump_scale_lineage_guards()`` SECURITY DEFINER trigger function
(spec §7.3's revision-bump mechanism) -- in the same migration file (not a
new one), per the plan's Task 7/8 file-structure note. The remaining
Candidate/EvidenceSnapshot/ActivationPreview tables are later tasks' job.

Task 8's trigger function is owned by whichever role runs this migration
(``marketai_domain_owner`` in every deployed environment, per
``deploy/postgres/domain-tenant-roles.sql``, which is already ``BYPASSRLS``)
-- no explicit ``ALTER FUNCTION ... OWNER TO`` is needed for it to bypass
``scale_lineage_guards``'s ``FORCE ROW LEVEL SECURITY`` from inside a
trigger fired on an unrelated table, matching every other SECURITY DEFINER
function in this codebase (e.g. ``g1a2b3c4d5e6_workspace_projection_
functions.py``). ``EXECUTE`` is revoked from PUBLIC: only the trigger
mechanism itself may invoke it, never a caller.

``scale_delivery_targets``'s composite FKs need exact composite unique
targets on tables this migration does not otherwise touch. Three of those
targets are added here as plain ``ALTER TABLE`` (not autogenerated,
matching the pattern the spec calls for in §4.3's closing paragraph):

* ``meta_connection_records`` gains
  ``(workspace_id, meta_mode, id, ad_account_id)``.
* ``observation_contract_generation_records`` gains
  ``(workspace_id, meta_mode, id, meta_connection_id, ad_account_id)`` and
  ``(workspace_id, meta_mode, id, meta_connection_id)``.
* ``evidence_publication_records`` gains
  ``(workspace_id, meta_mode, id, sync_run_id)``.

A fourth composite FK the spec calls for -- ``source_attestation_id`` ->
``evidence_attestation_records(workspace_id, meta_mode, id,
contract_generation_id, sync_run_id, publication_id)`` -- is NOT installed.
``evidence_attestation_records`` has no ``sync_run_id`` column yet; adding
one is a schema change to a table this task does not own
(``app/meta/models.py``'s ``EvidenceAttestationRecord``), and is out of
this task's scope. ``source_attestation_id`` is still stored, still
required by ``ck_sdt_source_type_biconditional`` when
``source_type = 'evidence_observation'``, and still hashed into
``source_manifest_hash`` -- only the database-level FK proof is deferred.
See ``app/scale/models.py``'s ``ScaleDeliveryTargetRecord`` docstring.

Follows ``m23b_meta_domain_tables``'s pattern: build each table from its
already-mapped SQLAlchemy ``Table`` object rather than a hand-transcribed
``op.create_table()`` call, so the physical schema and the ORM metadata can
never disagree. RLS uses ``marketai_meta_context_is_current(workspace_id,
meta_mode)`` (the HMAC-verified, meta-mode-aware helper from
``m23a_meta_foundation``), not a raw ``current_setting`` comparison --
consistent with every other Scale/Meta-domain table (see
``f5eeeab4e9b9_scale_deterministic_evidence_and_advice`` and
``m23b_meta_domain_tables`` for the same reasoning).
"""
