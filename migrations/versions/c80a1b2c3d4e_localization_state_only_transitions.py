"""Permit only contracted Localization state transitions.

Revision ID: c80a1b2c3d4e
Revises: b79c2d3e4f5a

The original Localization migration attached the shared whole-row
append-only trigger to ``localized_copy_versions`` and
``localization_attempts``.  Both records are immutable headers except for
their explicit ``state`` machines, so production PostgreSQL rejected the
approval and Worker transitions the domain contract requires.

This migration keeps DELETE and every non-state UPDATE forbidden.  It
replaces only those two triggers with narrow forward-transition guards and
removes stale generated CHECK constraints that still excluded Localization
provider steps and localized AssetVersion origins.  Downgrade fails before
schema mutation when rows using the widened contracts already exist.
"""
from __future__ import annotations

from alembic import op


revision = "c80a1b2c3d4e"
down_revision = "z1a2b3c4d5e6"
branch_labels = None
depends_on = None


def _is_postgres() -> bool:
    return op.get_bind().dialect.name == "postgresql"


def upgrade() -> None:
    if not _is_postgres():
        return

    # The Localization migration added expanded named constraints but the
    # originals (generated by earlier batch migrations) remained attached as
    # well. PostgreSQL enforces both, so the obsolete constraints still
    # rejected every Localization provider step and localized AssetVersion.
    op.execute("""
        ALTER TABLE provider_call_attempts
        DROP CONSTRAINT IF EXISTS
        ck_provider_call_attempts_ck_provider_call_attempt_step_kind
    """)
    op.execute("""
        ALTER TABLE asset_versions
        DROP CONSTRAINT IF EXISTS
        ck_asset_versions_ck_asset_version_origin_kind
    """)

    op.execute("""
        CREATE OR REPLACE FUNCTION marketai_guard_localized_copy_version_mutation()
        RETURNS trigger
        LANGUAGE plpgsql
        SET search_path = pg_catalog, public
        AS $$
        BEGIN
            IF TG_OP = 'DELETE' THEN
                RAISE EXCEPTION 'DELETE denied on immutable-except-state table %',
                    TG_TABLE_NAME;
            END IF;

            IF (to_jsonb(NEW) - 'state') IS DISTINCT FROM
               (to_jsonb(OLD) - 'state') THEN
                RAISE EXCEPTION 'UPDATE denied outside state on immutable-except-state table %',
                    TG_TABLE_NAME;
            END IF;

            IF NOT (
                (OLD.state = 'draft' AND NEW.state IN ('needs_review', 'superseded'))
                OR (OLD.state = 'needs_review' AND NEW.state IN ('approved', 'superseded'))
                OR (OLD.state = 'approved' AND NEW.state = 'superseded')
            ) THEN
                RAISE EXCEPTION 'invalid localized copy state transition: % -> %',
                    OLD.state, NEW.state;
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    op.execute("""
        DROP TRIGGER trg_localized_copy_versions_append_only
        ON localized_copy_versions
    """)
    op.execute("""
        CREATE TRIGGER trg_localized_copy_versions_state_only
        BEFORE UPDATE OR DELETE ON localized_copy_versions
        FOR EACH ROW
        EXECUTE FUNCTION marketai_guard_localized_copy_version_mutation()
    """)

    op.execute("""
        CREATE OR REPLACE FUNCTION marketai_guard_localization_attempt_mutation()
        RETURNS trigger
        LANGUAGE plpgsql
        SET search_path = pg_catalog, public
        AS $$
        DECLARE
            has_terminal_provider_evidence boolean;
        BEGIN
            IF TG_OP = 'DELETE' THEN
                RAISE EXCEPTION 'DELETE denied on immutable-except-state table %',
                    TG_TABLE_NAME;
            END IF;

            IF (to_jsonb(NEW) - 'state') IS DISTINCT FROM
               (to_jsonb(OLD) - 'state') THEN
                RAISE EXCEPTION 'UPDATE denied outside state on immutable-except-state table %',
                    TG_TABLE_NAME;
            END IF;

            IF OLD.state = 'authorized' AND NEW.state = 'dispatching' THEN
                RETURN NEW;
            END IF;
            IF OLD.state = 'dispatching'
               AND NEW.state IN ('completed', 'failed', 'uncertain') THEN
                RETURN NEW;
            END IF;

            IF OLD.state = 'uncertain' AND NEW.state IN ('completed', 'failed') THEN
                SELECT EXISTS (
                    SELECT 1
                      FROM public.localization_item_provider_calls AS item_call
                      JOIN public.provider_call_attempts AS provider_attempt
                        ON provider_attempt.workspace_id = item_call.workspace_id
                       AND provider_attempt.id = item_call.provider_call_attempt_id
                     WHERE item_call.workspace_id = OLD.workspace_id
                       AND item_call.attempt_id = OLD.id
                       AND provider_attempt.dispatch_state = CASE NEW.state
                           WHEN 'completed' THEN 'succeeded'
                           ELSE 'failed'
                       END
                ) INTO has_terminal_provider_evidence;
                IF has_terminal_provider_evidence THEN
                    RETURN NEW;
                END IF;
                RAISE EXCEPTION
                    'localization attempt reconciliation lacks terminal provider evidence: % -> %',
                    OLD.state, NEW.state;
            END IF;

            RAISE EXCEPTION 'invalid localization attempt state transition: % -> %',
                OLD.state, NEW.state;
        END;
        $$
    """)
    op.execute("""
        DROP TRIGGER trg_localization_attempts_append_only
        ON localization_attempts
    """)
    op.execute("""
        CREATE TRIGGER trg_localization_attempts_state_only
        BEFORE UPDATE OR DELETE ON localization_attempts
        FOR EACH ROW
        EXECUTE FUNCTION marketai_guard_localization_attempt_mutation()
    """)


def downgrade() -> None:
    if not _is_postgres():
        return

    # The previous release constraints excluded Localization provider steps
    # and localized AssetVersions. Re-adding them while newer rows exist would
    # either fail late after unrelated downgrade work or tempt an operator to
    # destroy evidence.
    # Fail before any schema mutation so PostgreSQL's transactional DDL leaves
    # the current contract intact and the incompatible rows untouched.
    op.execute("""
        DO $$
        BEGIN
            IF EXISTS (
                SELECT 1
                  FROM asset_versions
                 WHERE origin_kind = 'localized'
            ) THEN
                RAISE EXCEPTION
                    'cannot downgrade c80a1b2c3d4e: asset_versions contains localized origins unsupported by b79c2d3e4f5a';
            END IF;
            IF EXISTS (
                SELECT 1
                  FROM provider_call_attempts
                 WHERE step_kind NOT IN ('generation', 'visual_qc')
            ) THEN
                RAISE EXCEPTION
                    'cannot downgrade c80a1b2c3d4e: provider_call_attempts contains step_kind values unsupported by b79c2d3e4f5a';
            END IF;
        END;
        $$
    """)

    for table_name in ("localized_copy_versions", "localization_attempts"):
        op.execute(f"DROP TRIGGER trg_{table_name}_state_only ON {table_name}")
        op.execute(f"""
            CREATE TRIGGER trg_{table_name}_append_only
            BEFORE UPDATE OR DELETE ON {table_name}
            FOR EACH ROW EXECUTE FUNCTION marketai_reject_update_or_delete()
        """)

    op.execute("DROP FUNCTION marketai_guard_localization_attempt_mutation()")
    op.execute("DROP FUNCTION marketai_guard_localized_copy_version_mutation()")
    op.execute("""
        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1
                  FROM pg_constraint
                 WHERE conrelid = 'public.asset_versions'::regclass
                   AND conname =
                       'ck_asset_versions_ck_asset_version_origin_kind'
            ) THEN
                ALTER TABLE asset_versions
                ADD CONSTRAINT
                    ck_asset_versions_ck_asset_version_origin_kind
                CHECK (origin_kind IN (
                    'generation', 'upload', 'reuse', 'legacy'
                ));
            END IF;
        END;
        $$
    """)
    op.execute("""
        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1
                  FROM pg_constraint
                 WHERE conrelid = 'public.provider_call_attempts'::regclass
                   AND conname =
                       'ck_provider_call_attempts_ck_provider_call_attempt_step_kind'
            ) THEN
                ALTER TABLE provider_call_attempts
                ADD CONSTRAINT
                    ck_provider_call_attempts_ck_provider_call_attempt_step_kind
                CHECK (step_kind IN ('generation', 'visual_qc'));
            END IF;
        END;
        $$
    """)
