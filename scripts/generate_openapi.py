#!/usr/bin/env python3
"""Extracts a normalized OpenAPI 3.1 spec from the FastAPI app (spec §6.11).

`contracts/openapi/marketai-domain-v1.json` is the *source of truth* the
rest of the generation pipeline (`scripts/generate_*.ts`) reads — but its
`operationId`s, methods, paths and schemas must always match what FastAPI
actually serves at `/api/v1/*`, or the BFF allowlist would validate against
a contract the domain service does not implement. This script imports the
FastAPI app in-process (no running server or network hop required),
extracts only the versioned `/api/v1/*` routes, strips FastAPI/Pydantic's
autogenerated `title` noise, and writes a minimal, deterministic spec.

Unlike the seven `web/lib/domain-client/generated/*` artifacts (regenerated
unconditionally by `scripts/generate_all.sh`, drift-checked in CI), this
script is run manually whenever an `/api/v1/*` route or its `response_model`
changes — the same way `scripts/generate_all.sh`'s drift check catches a
forgotten `web` regeneration, running this script and diffing the result
catches a forgotten contract update after a FastAPI route change.

Usage: `python scripts/generate_openapi.py [--check]`
`--check` exits non-zero (without writing) if the extracted spec would
differ from the committed file — for CI.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parent.parent
CONTRACT_PATH = ROOT_DIR / "contracts" / "openapi" / "marketai-domain-v1.json"

API_PREFIX = "/api/v1/"

# FastAPI has no first-class concept of a shared RFC 9457 Problem Details
# response schema — it is produced by this app's exception handlers, not a
# per-route `response_model`, so no route's introspected schema carries it.
# Hand-defined here and merged into every extracted spec (spec §9).
PROBLEM_DETAILS_SCHEMA: dict[str, Any] = {
    "type": "object",
    "required": ["type", "title", "status", "code", "trace_id", "retryable"],
    "properties": {
        "type": {"type": "string"},
        "title": {"type": "string"},
        "status": {"type": "integer"},
        "detail": {"type": "string"},
        "instance": {"type": "string"},
        "code": {"type": "string"},
        # Values the interface's `error-<code>` copy interpolates (#253);
        # `detail` is a diagnostic for logs and audit, never rendered.
        "params": {"type": "object", "additionalProperties": True},
        "trace_id": {"type": "string"},
        "retryable": {"type": "boolean"},
        "field_errors": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "field": {"type": "string"},
                    "code": {"type": "string"},
                    "detail": {"type": "string"},
                    "params": {"type": "object", "additionalProperties": True},
                },
            },
        },
    },
}


def _strip_titles(node: Any) -> Any:
    """Drop schema ``title`` annotations without deleting a field named ``title``."""
    if isinstance(node, dict):
        cleaned: dict[str, Any] = {}
        for key, value in node.items():
            if key == "title":
                continue
            if key == "properties" and isinstance(value, dict):
                cleaned[key] = {
                    property_name: _strip_titles(property_schema)
                    for property_name, property_schema in value.items()
                }
            else:
                cleaned[key] = _strip_titles(value)
        return cleaned
    if isinstance(node, list):
        return [_strip_titles(item) for item in node]
    return node


def _normalize_responses(responses: dict[str, Any]) -> dict[str, Any]:
    """Describe the app's exception-handler surface, not FastAPI's default.

    FastAPI injects an ``application/json`` ``HTTPValidationError`` 422 into
    route OpenAPI metadata. MarketAI replaces that runtime response (and all
    other HTTP errors) with RFC 9457 Problem Details. If the extracted
    contract retains FastAPI's default, the BFF's startup binding check
    correctly fails closed before the first domain request.
    """
    normalized: dict[str, Any] = {}
    for status, response in responses.items():
        try:
            is_error = int(status) >= 400
        except (TypeError, ValueError):
            is_error = False

        if is_error:
            normalized[status] = {
                "description": response.get("description", "Problem Details"),
                "content": {
                    "application/problem+json": {
                        "schema": {
                            "$ref": "#/components/schemas/ProblemDetails"
                        }
                    }
                },
            }
        else:
            normalized[status] = _strip_titles(response)
    return normalized


def _collect_referenced_schemas(
    node: Any, all_schemas: dict[str, Any], out: dict[str, Any]
) -> None:
    """BFS over `$ref` pointers starting from the retained paths, so only schemas actually reachable from `/api/v1/*` operations are kept."""
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            name = ref.rsplit("/", 1)[-1]
            if name not in out and name in all_schemas:
                out[name] = all_schemas[name]
                _collect_referenced_schemas(all_schemas[name], all_schemas, out)
        for value in node.values():
            _collect_referenced_schemas(value, all_schemas, out)
    elif isinstance(node, list):
        for item in node:
            _collect_referenced_schemas(item, all_schemas, out)


def extract_spec() -> dict[str, Any]:
    # Imported lazily: importing app.main has side effects (loads config,
    # builds the delegated-identity middleware stack) that should only run
    # when this script actually executes, not on module import for tooling
    # that merely inspects this file (e.g. a future test importing helpers).
    # Runnable as `python scripts/generate_openapi.py` from any cwd, so the
    # repo root is added to sys.path explicitly rather than relying on
    # whatever directory the interpreter was launched from.
    if str(ROOT_DIR) not in sys.path:
        sys.path.insert(0, str(ROOT_DIR))
    from app.main import app  # noqa: PLC0415

    raw = app.openapi()

    versioned_paths: dict[str, Any] = {}
    for path_template, path_item in raw.get("paths", {}).items():
        if not path_template.startswith(API_PREFIX):
            continue
        operations: dict[str, Any] = {}
        for method, operation in path_item.items():
            if method not in {"get", "put", "post", "delete", "options", "head", "patch", "trace"}:
                continue
            operation_id = operation.get("operationId")
            if not operation_id:
                raise SystemExit(
                    f"{method.upper()} {path_template} has no operationId — "
                    "every /api/v1/* route must set operation_id= explicitly "
                    "so the generated OperationEntry keys match this contract."
                )
            cleaned: dict[str, Any] = {"operationId": operation_id}
            if operation.get("summary"):
                cleaned["summary"] = operation["summary"]
            if operation.get("description"):
                cleaned["description"] = operation["description"]
            # A frozen operation (`deprecated=True`, e.g. #337's legacy
            # test-plan commands) stays in the contract and is marked so.
            if operation.get("deprecated"):
                cleaned["deprecated"] = True
            if operation.get("parameters"):
                cleaned["parameters"] = _strip_titles(operation["parameters"])
            if operation.get("requestBody"):
                cleaned["requestBody"] = _strip_titles(operation["requestBody"])
            # Vendor extensions (e.g. `x-marketai-idempotent`, spec §6.2.3)
            # are set via a route's `openapi_extra=` and must survive
            # extraction -- `scripts/lib/spec.ts`'s `isIdempotent()` and the
            # generators that call it read these directly off this
            # committed contract, not off any FastAPI-specific shape.
            for key, value in operation.items():
                if key.startswith("x-"):
                    cleaned[key] = value
            cleaned["responses"] = _normalize_responses(
                operation.get("responses", {})
            )
            operations[method] = cleaned
        if operations:
            versioned_paths[path_template] = operations

    all_schemas = raw.get("components", {}).get("schemas", {})
    referenced_schemas: dict[str, Any] = {}
    _collect_referenced_schemas(versioned_paths, all_schemas, referenced_schemas)
    referenced_schemas = {
        name: _strip_titles(schema) for name, schema in referenced_schemas.items()
    }
    # ProblemDetails is part of the contract's shared error surface (spec
    # §9) even though no single route's response_model references it yet.
    referenced_schemas.setdefault("ProblemDetails", PROBLEM_DETAILS_SCHEMA)

    spec: dict[str, Any] = {
        "openapi": "3.1.0",
        "info": {
            "title": "MarketAI Domain API",
            "version": "1.0.0",
            "description": (
                "Contract for the FastAPI domain service reached through the BFF "
                "catch-all proxy (spec §4.10, §6). Extracted from the running "
                "FastAPI app by scripts/generate_openapi.py — do not hand-edit "
                "paths or schemas without also updating the corresponding "
                "/api/v1/* route."
            ),
        },
        "paths": {path: versioned_paths[path] for path in sorted(versioned_paths)},
        "components": {
            "schemas": {
                name: referenced_schemas[name] for name in sorted(referenced_schemas)
            }
        },
    }
    return spec


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the extracted spec differs from the committed file, without writing.",
    )
    args = parser.parse_args()

    os.environ.setdefault("DATABASE_URL", "sqlite:///:memory:")
    spec = extract_spec()
    serialized = json.dumps(spec, indent=2, ensure_ascii=False) + "\n"

    if args.check:
        current = CONTRACT_PATH.read_text() if CONTRACT_PATH.exists() else ""
        if current != serialized:
            sys.stderr.write(
                f"{CONTRACT_PATH} is out of date with the running FastAPI app. "
                "Run `python scripts/generate_openapi.py` and commit the result.\n"
            )
            return 1
        return 0

    CONTRACT_PATH.write_text(serialized)
    print(f"Wrote {CONTRACT_PATH.relative_to(ROOT_DIR)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
