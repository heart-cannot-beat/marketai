#!/usr/bin/env node
/**
 * Dependency and licence inventory for the imported control-plane source.
 *
 * Reads the resolved dependency tree from package-lock.json and writes
 * THIRD-PARTY-LICENSES.md plus the machine-readable dependency-inventory.json.
 *
 * The lockfile is the source of truth rather than the installed node_modules
 * tree: npm only unpacks the optional platform binaries matching the current
 * os/cpu, so a node_modules walk yields a different package set on macOS than
 * on the Linux CI runner and the --check form can never agree across hosts.
 * The lockfile lists every variant with its licence, so the inventory is both
 * complete and reproducible anywhere.
 *
 *   node scripts/license-inventory.mjs          # regenerate
 *   node scripts/license-inventory.mjs --check  # fail if the committed files drift
 *
 * CI runs the --check form so a dependency change cannot land without an
 * updated inventory.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const directDependencies = new Set(Object.keys(pkg.dependencies ?? {}));
const directDevDependencies = new Set(Object.keys(pkg.devDependencies ?? {}));

const normaliseLicense = (entry) => {
  if (typeof entry.license === 'string') return entry.license;
  if (entry.license?.type) return entry.license.type;
  if (Array.isArray(entry.licenses)) {
    return entry.licenses.map((l) => l.type ?? l).join(' OR ');
  }
  return 'UNKNOWN';
};

/** "node_modules/a/node_modules/@scope/b" -> "@scope/b" */
const nameFromLockPath = (path) => {
  const marker = 'node_modules/';
  return path.slice(path.lastIndexOf(marker) + marker.length);
};

const collect = () => {
  const lock = JSON.parse(
    readFileSync(join(root, 'package-lock.json'), 'utf8')
  );
  const acc = new Map();

  for (const [path, entry] of Object.entries(lock.packages ?? {})) {
    // The empty key is the workspace root itself, not a dependency.
    if (!path.startsWith('node_modules/')) continue;

    const name = entry.name ?? nameFromLockPath(path);
    const key = `${name}@${entry.version}`;
    if (acc.has(key)) continue;

    acc.set(key, {
      name,
      version: entry.version,
      license: normaliseLicense(entry),
      // The lockfile carries no repository field; the registry tarball is the
      // deterministic provenance record and is what npm actually fetches.
      resolved: entry.resolved ?? null,
      direct: directDependencies.has(name)
        ? 'dependency'
        : directDevDependencies.has(name)
          ? 'devDependency'
          : 'transitive',
      // Recorded so a platform-specific binary is visibly platform-specific
      // instead of silently appearing or vanishing with the build host.
      ...(entry.os || entry.cpu
        ? { platform: { os: entry.os ?? null, cpu: entry.cpu ?? null } }
        : {}),
    });
  }

  return acc;
};

const packages = [...collect().values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
);

const licenseCounts = packages.reduce((acc, p) => {
  acc[p.license] = (acc[p.license] ?? 0) + 1;
  return acc;
}, {});

const upstream = JSON.parse(readFileSync(join(root, 'UPSTREAM.json'), 'utf8'));

const inventory = {
  component: pkg.name,
  generatedBy: 'web/scripts/license-inventory.mjs',
  vendoredSource: {
    name: upstream.upstream.name,
    repository: upstream.upstream.repository,
    pinnedCommit: upstream.upstream.pinnedCommit,
    license: upstream.upstream.license,
  },
  totals: {
    packages: packages.length,
    direct: packages.filter((p) => p.direct !== 'transitive').length,
    platformSpecific: packages.filter((p) => p.platform).length,
    licenses: licenseCounts,
  },
  packages,
};

const markdown = [
  '# Third-party dependency and licence inventory',
  '',
  'Generated by `web/scripts/license-inventory.mjs`. Do not edit by hand; run',
  '`npm run inventory:licenses` after any dependency change. CI runs',
  '`npm run inventory:licenses:check` and fails on drift.',
  '',
  '## Vendored source',
  '',
  `- **${inventory.vendoredSource.name}** — ${inventory.vendoredSource.license}`,
  `  - ${inventory.vendoredSource.repository}`,
  `  - pinned at \`${inventory.vendoredSource.pinnedCommit}\``,
  '',
  '## Totals',
  '',
  `- Locked packages: ${inventory.totals.packages}`,
  `- Declared directly in \`package.json\`: ${inventory.totals.direct}`,
  `- Platform-specific optional binaries: ${inventory.totals.platformSpecific}`,
  '',
  '| Licence | Packages |',
  '| --- | ---: |',
  ...Object.entries(licenseCounts)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([license, count]) => `| ${license} | ${count} |`),
  '',
  '## Packages',
  '',
  '| Package | Version | Licence | Kind |',
  '| --- | --- | --- | --- |',
  ...packages.map(
    (p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.direct} |`
  ),
  '',
].join('\n');

const jsonPath = join(root, 'dependency-inventory.json');
const mdPath = join(root, 'THIRD-PARTY-LICENSES.md');
const jsonBody = `${JSON.stringify(inventory, null, 2)}\n`;

if (check) {
  const drift = [];

  if (!existsSync(jsonPath) || readFileSync(jsonPath, 'utf8') !== jsonBody) {
    drift.push('dependency-inventory.json');
  }
  if (!existsSync(mdPath) || readFileSync(mdPath, 'utf8') !== markdown) {
    drift.push('THIRD-PARTY-LICENSES.md');
  }

  if (drift.length) {
    process.stderr.write(
      `Dependency inventory is out of date: ${drift.join(', ')}\n` +
        'Run: npm run inventory:licenses\n'
    );
    process.exit(1);
  }

  process.stdout.write(
    `Dependency inventory up to date (${packages.length} packages)\n`
  );
  process.exit(0);
}

writeFileSync(jsonPath, jsonBody);
writeFileSync(mdPath, markdown);

process.stdout.write(
  `Wrote dependency inventory for ${packages.length} packages\n`
);
