-- MarketAI control-plane baseline.
--
-- This fork does not carry the upstream BoxyHQ migration history. The upstream
-- chain creates ApiKey, Subscription, Service, Price and the three jackson_*
-- tables and the three-value Role enum, all of which this fork removed. Replaying
-- it and then dropping those objects would ship a destructive migration for
-- tables that never existed in any MarketAI environment, so the history is
-- squashed to one reviewed baseline instead.
--
-- Invitation carries no `sentViaEmail`/`allowedDomains` columns and `email` is
-- NOT NULL: an invitation is addressed to exactly one email address, and the
-- shareable-link mode upstream supported cannot be represented.
--
-- Applied with `prisma migrate deploy` as a separate release step, running as
-- the schema-owner role (MIGRATION_DATABASE_URL), never as the runtime role.
-- `prisma db push` is not part of any build or release path.

